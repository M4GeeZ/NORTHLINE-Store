import {createInterface} from 'node:readline/promises';
import {stdin as input,stdout as output} from 'node:process';
import {randomBytes} from 'node:crypto';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const target=path.join(root,'server','.env');
const rl=createInterface({input,output});
try{
 console.log('\nNORTHLINE • MERN local setup\n');
 try{const existing=await readFile(target,'utf8');if(existing.trim()){const answer=await rl.question('server/.env exists. Overwrite it? (type YES): ');if(answer!=='YES'){console.log('Existing configuration preserved.');process.exit(0)}}}catch(e){if(e.code!=='ENOENT')throw e}
 const raw=(await rl.question('Paste your complete Atlas Drivers connection URI: ')).trim();
 if(!raw.startsWith('mongodb+srv://')&&!raw.startsWith('mongodb://'))throw new Error('Atlas URI must start with mongodb+srv:// (or mongodb://).');
 if(/<|>|YOUR_|db_password|:PASSWORD@|127\.0\.0\.1|localhost/i.test(raw))throw new Error('The URI still contains placeholders or points at local MongoDB. Copy the Atlas Drivers URI and replace its password.');
 const uri=new URL(raw);
 if(!uri.hostname||!uri.username||!uri.password)throw new Error('URI must include a host, database username and database password.');
 if(uri.pathname==='/')uri.pathname='/codealpha_northline';
 const port='5000'; // Matches the Vite development proxy in client/vite.config.js.
 const secret=randomBytes(48).toString('hex');
 const contents=`# Generated by npm run setup; NEVER commit this file.\nPORT=${port}\nMONGO_URI=${uri.toString()}\nJWT_SECRET=${secret}\nCLIENT_URL=http://localhost:5173\nNODE_ENV=development\nAUTO_SEED=true\n\n# Email settings (after setup, add a Gmail App Password manually)\nSTORE_OWNER_EMAIL=mughees1275@gmail.com\nSMTP_USER=mughees1275@gmail.com\nSMTP_APP_PASSWORD=REPLACE_WITH_GMAIL_16_CHAR_APP_PASSWORD\nSTORE_PUBLIC_URL=http://localhost:5173\n`;
 await mkdir(path.dirname(target),{recursive:true});await writeFile(target,contents,{mode:0o600});
 console.log('\n✅ server/.env created successfully.');
 console.log('✅ Strong JWT secret generated.');
 console.log('✅ Database selected: '+uri.pathname.slice(1));
 console.log('\nNext: npm install (if not installed), then npm run dev.');
 console.log('For Atlas, check Database Access and Network Access if connection fails.');
 console.log('For email alerts, replace SMTP_APP_PASSWORD in server/.env with a Gmail App Password.');
}catch(e){console.error('\nSetup error:',e.message);process.exitCode=1}finally{rl.close()}
